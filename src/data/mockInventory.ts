const ledger = (entries: Omit<InventoryItem["ledger"][number], "id">[]): InventoryItem["ledger"] =>
  entries.map((entry, index) => ({ ...entry, id: `ledger-${index}-${entry.occurredAt}` }));

const components = (itemId: string, rows: Omit<JewelryComponent, "id">[]): JewelryComponent[] =>
  rows.map((row, index) => ({ ...row, id: `${itemId}-c${index + 1}` }));

